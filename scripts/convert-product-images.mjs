/**
 * Converts product + work images to AVIF and removes source PNG/JPEG files.
 * Run: npm run convert-images
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const productsDir = path.join(root, 'public/images/products');
const workDir = path.join(root, 'public/work');
const heroManifest = path.join(root, 'src/lib/hero-images.generated.ts');

const PRODUCT_SLUG_BY_SOURCE = {
  'Wheat.png': 'wheat',
  'Pearl Millet.png': 'bajra',
  'Chickpeas.png': 'chana',
  'Green Gram.png': 'moong',
  'Toor Dal.png': 'toor-dal',
  'Wheat Flour.png': 'wheat-flour',
  'Potato Wafers.png': 'potato-wafers',
  'Potato Chips.png': 'potato-chips',
  'Mustard Seeds.png': 'mustard',
  'Cumin.png': 'cumin',
};

const SOURCE_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp']);

async function convertToAvif(input, output, maxWidth = 1600) {
  await sharp(input)
    .resize(maxWidth, maxWidth, { fit: 'inside', withoutEnlargement: true })
    .avif({ quality: 62, effort: 4 })
    .toFile(output);
}

async function convertProducts() {
  const paths = [];
  console.log('\nProducts:');
  for (const [source, slug] of Object.entries(PRODUCT_SLUG_BY_SOURCE)) {
    const input = path.join(productsDir, source);
    const output = path.join(productsDir, `${slug}.avif`);
    if (!fs.existsSync(input)) {
      if (fs.existsSync(output)) {
        paths.push(`/images/products/${slug}.avif`);
        console.log(`  keep existing ${slug}.avif`);
      } else {
        console.warn(`  skip (missing): ${source}`);
      }
      continue;
    }
    await convertToAvif(input, output, 1200);
    fs.unlinkSync(input);
    const outKb = Math.round(fs.statSync(output).size / 1024);
    console.log(`  ${source} → ${slug}.avif (${outKb}KB), removed source`);
    paths.push(`/images/products/${slug}.avif`);
  }

  // Remove any leftover PNG/JPEG in products (not avif)
  for (const file of fs.readdirSync(productsDir)) {
    const ext = path.extname(file).toLowerCase();
    if (SOURCE_EXTS.has(ext)) {
      fs.unlinkSync(path.join(productsDir, file));
      console.log(`  removed leftover ${file}`);
    }
  }

  return paths;
}

async function convertWork() {
  const paths = [];
  if (!fs.existsSync(workDir)) {
    fs.mkdirSync(workDir, { recursive: true });
    return paths;
  }

  console.log('\nWork:');
  const sources = fs
    .readdirSync(workDir)
    .filter((f) => SOURCE_EXTS.has(path.extname(f).toLowerCase()))
    .sort();

  let i = 1;
  for (const source of sources) {
    const slug = `work-${String(i).padStart(2, '0')}`;
    const input = path.join(workDir, source);
    const output = path.join(workDir, `${slug}.avif`);
    await convertToAvif(input, output, 1920);
    fs.unlinkSync(input);
    const outKb = Math.round(fs.statSync(output).size / 1024);
    console.log(`  ${source} → ${slug}.avif (${outKb}KB), removed source`);
    paths.push(`/work/${slug}.avif`);
    i += 1;
  }

  // Keep existing work-*.avif if no sources left
  if (paths.length === 0) {
    for (const file of fs.readdirSync(workDir)) {
      if (file.endsWith('.avif')) {
        paths.push(`/work/${file}`);
        console.log(`  keep existing ${file}`);
      }
    }
  }

  return paths.sort();
}

/** Work images excluded from hero carousel */
const HERO_EXCLUDED = new Set(['work-05.avif']);

function writeManifest(_productPaths, workPaths) {
  const heroPaths = workPaths.filter((p) => !HERO_EXCLUDED.has(p.replace('/work/', '')));
  const content = `/** Auto-generated by scripts/convert-product-images.mjs — do not edit manually */
/** Hero carousel uses work photos only (not product catalogue images). */
export const HERO_CAROUSEL_IMAGES: string[] = ${JSON.stringify(heroPaths, null, 2)};
`;
  fs.writeFileSync(heroManifest, content, 'utf8');
  console.log(`\nWrote ${heroPaths.length} hero paths (work folder only) to src/lib/hero-images.generated.ts`);
}

async function main() {
  const productPaths = await convertProducts();
  const workPaths = await convertWork();
  writeManifest(productPaths, workPaths);
  console.log('Done.');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
